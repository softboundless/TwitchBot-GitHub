// Deterministic rejection of common instruction overrides, before any API call.
// This is a narrow guard, not a complete prompt-injection detector.
export function isTarotOverride(text) {
  const normalized = String(text).normalize('NFKC').replace(/\p{Cf}/gu, '').toLowerCase();
  return /(?:игнор\p{L}*|забудь|отмени|отменить|не\s+соблюдай)[\s\S]{0,100}(?:инструкц|указани|правил|промпт)/u.test(normalized)
    || /(?:ignore|forget|disregard|override)[\s\S]{0,100}(?:instructions?|rules?|prompts?)/u.test(normalized)
    || /(?:раскрой|покажи|выведи|повтори)[\s\S]{0,60}(?:системн\p{L}*\s+(?:промпт|инструкц))/u.test(normalized)
    || /(?:<\|(?:im_start|start|system)\|>|\[inst\]|<<sys>>)/u.test(normalized);
}

